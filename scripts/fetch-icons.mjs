// Vendors the Lucide icons the app uses into extension/lib/icons.js (extension pages can't load remote code).
// Lucide is ISC licensed: https://lucide.dev/license
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const VERSION = '0.460.0';
const NAMES = [
  'layout-dashboard', 'trophy', 'palette', 'activity', 'sliders-horizontal', 'share-2', 'user-round', 'chevrons-up-down',
  'sun', 'moon', 'monitor', 'log-out', 'trash-2', 'copy', 'external-link', 'check', 'link', 'refresh-cw', 'x',
  'key-round', 'chevron-left', 'chevron-right', 'flame', 'coins', 'snowflake', 'droplet', 'heart', 'eye', 'eye-off',
  'circle-check', 'circle-alert', 'sparkles', 'gift', 'target', 'calendar-days', 'lock', 'plug-zap', 'arrow-right',
  'smartphone', 'settings', 'cloud-off', 'star', 'shopping-bag', 'menu',
];
const out = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'extension', 'lib', 'icons.js');

const icons = {};
for (const name of NAMES) {
  const r = await fetch(`https://unpkg.com/lucide-static@${VERSION}/icons/${name}.svg`);
  if (!r.ok) throw new Error(`${name}: ${r.status}`);
  const svg = await r.text();
  icons[name] = svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>')).replace(/\s+/g, ' ').trim();
}
const body = `// Generated by scripts/fetch-icons.mjs from lucide-static@${VERSION} (ISC license, https://lucide.dev/license).
const PATHS = ${JSON.stringify(icons, null, 1)};

/** Inline SVG markup for a Lucide icon. */
export function icon(name, size = 16, cls = '') {
  return \`<svg class="icon \${cls}" width="\${size}" height="\${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">\${PATHS[name] || ''}</svg>\`;
}
`;
await fs.writeFile(out, body);
console.log(`wrote ${Object.keys(icons).length} icons`);
